#!/usr/bin/env bash
# Generate TypeScript types for the database schema.
# Uses $DATABASE_URL if set, otherwise boots an ephemeral local cluster with
# all migrations applied, then runs `supabase gen types`.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/apps/web/src/lib/supabase/database.types.ts"

PG_BIN="${PG_BIN:-}"
if [[ -z "$PG_BIN" ]]; then
  for candidate in /opt/homebrew/opt/postgresql@17/bin /usr/local/opt/postgresql@17/bin /usr/lib/postgresql/17/bin; do
    if [[ -x "$candidate/psql" ]]; then PG_BIN="$candidate"; break; fi
  done
fi
[[ -n "$PG_BIN" ]] && export PATH="$PG_BIN:$PATH"

SUPABASE_BIN="${SUPABASE_BIN:-supabase}"
if ! command -v "$SUPABASE_BIN" >/dev/null 2>&1; then
  for candidate in /opt/homebrew/bin/supabase /usr/local/bin/supabase; do
    [[ -x "$candidate" ]] && SUPABASE_BIN="$candidate" && break
  done
fi

cleanup() {
  if [[ -n "${PGDATA_TMP:-}" ]]; then
    pg_ctl -D "$PGDATA_TMP" stop -m immediate >/dev/null 2>&1 || true
    rm -rf "$PGDATA_TMP"
  fi
}
trap cleanup EXIT

if [[ -z "${DATABASE_URL:-}" ]]; then
  PGDATA_TMP="$(mktemp -d /tmp/lawnquoter-pg.XXXXXX)"
  PORT="${PGPORT_TYPES:-54331}"
  initdb -D "$PGDATA_TMP" -U postgres --auth=trust >/dev/null
  pg_ctl -D "$PGDATA_TMP" -o "-p $PORT -k $PGDATA_TMP -c listen_addresses=127.0.0.1" -l "$PGDATA_TMP/server.log" start >/dev/null
  psql "postgres://postgres@127.0.0.1:$PORT/postgres" -q -c "create database lawnquoter_types;" >/dev/null
  DATABASE_URL="postgres://postgres@127.0.0.1:$PORT/lawnquoter_types?sslmode=disable"
  PSQL=(psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -q)
  "${PSQL[@]}" -c "create extension if not exists pgcrypto;" >/dev/null
  "${PSQL[@]}" -f "$ROOT/supabase/tests/_shim/00_supabase_shim.sql" >/dev/null
  for f in $(ls "$ROOT"/supabase/migrations/*.sql | sort); do
    "${PSQL[@]}" -f "$f" >/dev/null
  done
fi

"$SUPABASE_BIN" gen types typescript --db-url "$DATABASE_URL" --schema public > "$OUT.tmp"
{
  echo "// Generated by \`pnpm db:types\`. Do not edit by hand."
  cat "$OUT.tmp"
} > "$OUT"
rm -f "$OUT.tmp"
echo "wrote $OUT"
